TEMPLATES = {
    'none': ('无模板', ''),
    'science': ('科技类', '以信、达、雅为标准翻译科技内容，准确保留事实、逻辑、公式、数值和单位。'
                '使用已有且准确的中文术语；对无法准确翻译、尚无中文解释或公认中文译名的术语，'
                '保留原文，不要硬译或杜撰解释。全书术语保持一致。'),
    'fiction': ('小说类', '以信、达、雅为标准翻译小说，忠实于情节、人物关系、叙述视角和作者语气。'
                '语言优美流畅、自然耐读；人名、地名、称谓及专有名词采用统一译法，'
                '参考前文已使用的译名，不要前后不一致影响阅读。不得增删情节或自行解释。'),
    'tutorial': ('教程类', '以平实、准确、容易理解的中文翻译教程，保留步骤、条件、操作顺序和技术含义。'
                 '已有准确中文译名的技术术语采用标准译名；没有可靠中文译名的保留原文。'
                 '程序代码、命令、变量、函数名、路径、字符串字面量及占位符保持原样，'
                 '只翻译自然语言注释，保留注释符号、缩进与换行，不改变代码行为。'),
    'magazine': ('杂志类', '根据杂志文章的主题、栏目与上下文进行翻译，结合文章发表时的时事背景理解用语与指代。'
                 '以信、达、雅为标准，语言平实流畅，准确传达原意、事实与作者语气。'
                 '保留原文日期、人物、事件与数据，不擅自补充、更新或编造时事信息。'
                 '尤其注意保留原格式、版式结构、标题层级、段落、列表、表格、图注及强调样式；'
                 '只翻译文字，不增删内容、不改写排版。'),
}


def combine_requirements(manual, template='none'):
    if template not in TEMPLATES:
        raise ValueError('未知的翻译模板')
    preset = TEMPLATES[template][1]
    if not preset:
        return manual.strip()
    parts = []
    if manual.strip():
        parts.append('用户手工要求（与模板冲突时优先）：\n' + manual.strip())
    if preset:
        parts.append('翻译类型模板：\n' + preset)
    return '\n\n'.join(parts)
