import json
from pathlib import Path
import subprocess
from zipfile import ZipFile

from lxml import etree
import pytest

import engine
from translation_client import TranslationClient


def run_calibre(command):
    result = subprocess.run([str(arg) for arg in command], capture_output=True, text=True,
                            encoding='utf-8', errors='replace', timeout=120,
                            creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
    assert result.returncode == 0, result.stdout + result.stderr
    return result


def test_real_azw3_edit_roundtrip(epub, tmp_path, api_server, monkeypatch):
    calibre = engine.find_calibre_debug()
    if calibre is None:
        pytest.skip('Calibre is required for the real AZW3 roundtrip')
    converter = calibre.with_name('ebook-convert.exe' if calibre.suffix == '.exe' else 'ebook-convert')
    if not converter.exists():
        pytest.skip('ebook-convert is required to create the AZW3 test fixture')
    source = tmp_path / 'book.azw3'
    # Conversion is only used to CREATE the fixture. The app edits AZW3 directly.
    run_calibre([converter, epub, source, '--no-inline-toc'])
    original = source.read_bytes()
    before_bundle = tmp_path / 'before.zip'
    runner = [calibre, '-e', engine.AZW3_RUNNER, '--']
    run_calibre(runner + ['export', source, before_bundle])
    endpoint, requests = api_server
    monkeypatch.setattr(engine, 'TranslationClient', lambda model, req, log, cancel, **options: TranslationClient(model, req, log, cancel, endpoint, **options))
    output = engine.translate(source, 'mock', '保留术语', tmp_path / 'output', on_line=lambda _: None)
    assert source.read_bytes() == original
    assert output.suffix == '.azw3'
    after_bundle = tmp_path / 'after.zip'
    run_calibre(runner + ['export', output, after_bundle])
    with ZipFile(before_bundle) as before, ZipFile(after_bundle) as after:
        assert set(before.namelist()) == set(after.namelist())
        all_text = ''.join(after.read(name).decode('utf-8') for name in after.namelist())
        assert '译文：' in all_text
        assert '保留术语' in requests[0][1]['messages'][0]['content']
        for name in before.namelist():
            if name.lower().endswith('.css'):
                continue
            # Calibre may regenerate navigation labels/IDs on save. Inline style
            # elements and their attributes in chapter documents must survive.
            a, b = etree.fromstring(before.read(name)), etree.fromstring(after.read(name))
            for tag in ['b', 'i', 'table', 'img', 'a']:
                left = a.xpath(f'//*[local-name()="{tag}"]')
                right = b.xpath(f'//*[local-name()="{tag}"]')
                assert len(left) == len(right), (name, tag)
                for x, y in zip(left, right):
                    # Kindle links/resource URLs can be regenerated by Calibre.
                    for attribute in ['class', 'style', 'width', 'height']:
                        assert x.get(attribute) == y.get(attribute)
    # Compare binary image/font and CSS data through Calibre's original container.
    inspect_script = tmp_path / 'inspect_resources.py'
    inspect_script.write_text('''import sys, json, hashlib
from calibre.ebooks.oeb.polish.container import get_container
from tempfile import TemporaryDirectory
with TemporaryDirectory() as tmp:
    c = get_container(sys.argv[1], tdir=tmp)
    data = {}
    for name, mime in c.mime_map.items():
        if mime == 'text/css' or mime.startswith(('image/', 'font/')):
            if mime == 'image/svg+xml': continue
            digest = hashlib.sha256(c.raw_data(name, decode=False)).hexdigest()
            data.setdefault(mime, []).append(digest)
    for values in data.values(): values.sort()
    print('RESOURCE_HASHES=' + json.dumps(data, sort_keys=True))
''', encoding='utf-8')
    def hashes(book):
        result = run_calibre([calibre, '-e', inspect_script, '--', book])
        return next(line for line in result.stdout.splitlines() if line.startswith('RESOURCE_HASHES='))
    assert hashes(source) == hashes(output)


@pytest.mark.parametrize('subtype', ['old', 'both', 'new'])
def test_mobi_variants(epub, tmp_path, api_server, monkeypatch, subtype):
    calibre = engine.find_calibre_debug()
    if calibre is None:
        pytest.skip('Calibre is required')
    converter = calibre.with_name('ebook-convert.exe' if calibre.suffix == '.exe' else 'ebook-convert')
    source = tmp_path / ('sample_' + subtype + '.mobi')
    run_calibre([converter, epub, source, '--mobi-file-type', subtype, '--no-inline-toc', '--mobi-keep-original-images'])
    original = source.read_bytes()
    endpoint, _ = api_server
    monkeypatch.setattr(engine, 'TranslationClient', lambda m, r, log, cancel, **options: TranslationClient(m, r, log, cancel, endpoint, **options))
    output = engine.translate(source, 'mock', '', tmp_path / 'out', on_line=lambda _: None)
    assert source.read_bytes() == original
    bundle = tmp_path / 'translated.zip'
    run_calibre([calibre, '-e', engine.AZW3_RUNNER, '--', 'export', output, bundle])
    with ZipFile(bundle) as archive:
        text = ''.join(archive.read(name).decode('utf-8') for name in archive.namelist())
    assert '译文：' in text
    assert output.suffix == '.mobi'
